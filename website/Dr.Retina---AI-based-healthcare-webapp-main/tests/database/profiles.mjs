import { PGlite } from "@electric-sql/pglite";
import fs from "node:fs";
import assert from "node:assert/strict";
const db = new PGlite();
await db.exec(`create role anon; create role authenticated; create schema auth;
create table auth.users(id uuid primary key);
create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
grant usage on schema auth to authenticated;
insert into auth.users values ('00000000-0000-4000-8000-000000000001');`);
const migration = fs.readdirSync("supabase/migrations").find(n => n.endsWith("_user_profiles.sql"));
await db.exec(fs.readFileSync("supabase/migrations/" + migration,"utf8"));
await db.exec(`insert into auth.users values ('00000000-0000-4000-8000-000000000002');`);
assert.equal((await db.query("select * from public.profiles")).rows.length,2);
await db.exec(`set role authenticated; select set_config('request.jwt.claim.sub','00000000-0000-4000-8000-000000000001',false);`);
assert.equal((await db.query("select * from public.profiles")).rows.length,1);
await db.exec("update public.profiles set display_name='My name'");
assert.equal((await db.query("select display_name from public.profiles")).rows[0].display_name,"My name");
assert.equal((await db.query("update public.profiles set display_name='Attack' where id='00000000-0000-4000-8000-000000000002' returning id")).rows.length,0);
await assert.rejects(db.exec("update public.profiles set id='00000000-0000-4000-8000-000000000002'"));
await assert.rejects(db.exec("delete from public.profiles"));
await assert.rejects(db.exec("insert into public.profiles(id) values ('00000000-0000-4000-8000-000000000003')"));
await assert.rejects(db.exec("select auth_private.create_user_profile()"));
await db.exec("reset role; set role anon");
await assert.rejects(db.exec("select * from public.profiles"));
await db.exec("reset role; delete from auth.users where id='00000000-0000-4000-8000-000000000001'");
assert.equal((await db.query("select * from public.profiles")).rows.length,1);
await db.close();
console.log("10 profile trigger, backfill, ownership, privilege and deletion checks passed.");
